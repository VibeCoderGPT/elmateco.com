  /* ============================================================================
     Moteur i18n (ne pas modifier)
     ============================================================================ */
  var current = 'en';
  try {
    var saved = window.localStorage.getItem(LS_KEY);
    if (saved && STR[saved]) current = saved;
  } catch (err) { /* stockage indisponible : on reste en anglais */ }

  function t(key) {
    var lang = STR[current];
    if (lang && lang[key]) return lang[key];
    return STR.en[key] || key;
  }

  function apply() {
    document.documentElement.lang = current;
    document.title = t('meta_title');
    var md = document.querySelector('meta[name="description"]');
    if (md) md.setAttribute('content', t('meta_desc'));

    document.querySelectorAll('[data-i18n]').forEach(function (el) {
      el.innerHTML = t(el.getAttribute('data-i18n'));
    });
    document.querySelectorAll('[data-i18n-attr]').forEach(function (el) {
      var attrs = el.getAttribute('data-i18n-attr').split(',');
      var key = el.getAttribute('data-i18n-key');
      attrs.forEach(function (a) { el.setAttribute(a, t(key)); });
    });

    var codeEl = document.getElementById('langCode');
    if (codeEl) codeEl.textContent = current.toUpperCase();
    refreshMenu();

    document.dispatchEvent(new CustomEvent('elm:langchange', { detail: { lang: current } }));
  }

  function setLang(code) {
    if (!STR[code]) return;
    if (code === current) { closeMenu(); return; }
    current = code;
    try { window.localStorage.setItem(LS_KEY, code); } catch (err) { /* silencieux */ }
    sweep();
    apply();
    closeMenu();
  }

  /* ---------- Sélecteur de langue (menu 🌐 en haut à droite) ---------- */
  var langBox = null, langBtn = null, langMenu = null;

  function buildMenu() {
    langBox = document.getElementById('langBox');
    langBtn = document.getElementById('langBtn');
    langMenu = document.getElementById('langMenu');
    var list = document.getElementById('langList');
    if (!langBox || !langBtn || !langMenu || !list) return;

    LANGS.forEach(function (L, i) {
      var b = document.createElement('button');
      b.type = 'button';
      b.className = 'lang-item';
      b.setAttribute('role', 'option');
      b.setAttribute('aria-selected', 'false');
      b.style.setProperty('--i', i);
      b.innerHTML = '<span class="flag" aria-hidden="true">' + L.flag + '</span>' +
                    '<span class="lname">' + L.label + '</span>' +
                    '<span class="check" aria-hidden="true">✓</span>';
      b.addEventListener('click', function () { setLang(L.code); });
      list.appendChild(b);
    });

    langBtn.addEventListener('click', function (e) {
      e.stopPropagation();
      toggleMenu();
    });
    document.addEventListener('pointerdown', function (e) {
      if (langBox && !langBox.contains(e.target)) closeMenu();
    });
    document.addEventListener('keydown', function (e) {
      if (e.key === 'Escape') closeMenu();
    });
    refreshMenu();
  }

  function toggleMenu() {
    if (!langMenu) return;
    var open = langMenu.classList.toggle('open');
    langBtn.setAttribute('aria-expanded', open ? 'true' : 'false');
  }
  function closeMenu() {
    if (!langMenu || !langMenu.classList.contains('open')) return;
    langMenu.classList.remove('open');
    langBtn.setAttribute('aria-expanded', 'false');
  }
  function refreshMenu() {
    var items = document.querySelectorAll('.lang-item');
    items.forEach(function (b, i) {
      var active = LANGS[i] && LANGS[i].code === current;
      b.classList.toggle('active', active);
      b.setAttribute('aria-selected', active ? 'true' : 'false');
    });
  }

  /* ---------- Balayage lumineux au changement de langue ---------- */
  var sweepTimer = null;
  function sweep() {
    if (window.matchMedia && window.matchMedia('(prefers-reduced-motion: reduce)').matches) return;
    var el = document.getElementById('langSweep');
    if (!el) {
      el = document.createElement('div');
      el.id = 'langSweep';
      el.className = 'lang-sweep';
      el.setAttribute('aria-hidden', 'true');
      document.body.appendChild(el);
    }
    document.documentElement.classList.remove('lang-switching');
    void el.offsetWidth; /* redémarre l'animation */
    document.documentElement.classList.add('lang-switching');
    clearTimeout(sweepTimer);
    sweepTimer = setTimeout(function () {
      document.documentElement.classList.remove('lang-switching');
    }, 800);
  }

  /* ---------- API publique ---------- */
  window.I18N = {
    LANGS: LANGS,
    STR: STR,
    get current() { return current; },
    t: t,
    apply: apply,
    setLang: setLang
  };
  window.t = t;

  /* ---------- Démarrage ---------- */
  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', function () {
      buildMenu();
      apply();
    });
  } else {
    buildMenu();
    apply();
  }
